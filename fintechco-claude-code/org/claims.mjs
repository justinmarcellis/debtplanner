#!/usr/bin/env node
// Merge claim shards into the register.
//   node org/claims.mjs     research/claims/*.json -> research/claims.json + research/claims.md
// Shards let parallel tickets source facts without writing the same file (ADR-006 addendum).
// Each shard owns an id range (org/contracts/README.md); a duplicate id across shards is an error.
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SHARDS = join(ROOT, 'research', 'claims');

/** Read every shard; return { claims, shardOf, duplicates }. */
export function mergeShards(dir = SHARDS) {
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.json')).sort() : [];
  const claims = [];
  const shardOf = {};
  const duplicates = [];
  for (const f of files) {
    for (const c of JSON.parse(readFileSync(join(dir, f), 'utf8'))) {
      if (shardOf[c.id]) duplicates.push(`${c.id} in ${shardOf[c.id]} and ${f}`);
      else { shardOf[c.id] = f; claims.push(c); }
    }
  }
  claims.sort((a, b) => a.id.localeCompare(b.id));
  return { claims, shardOf, duplicates };
}

/** Human-readable register. */
export function renderClaims(claims) {
  const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
  const counts = claims.reduce((m, c) => ({ ...m, [c.status]: (m[c.status] ?? 0) + 1 }), {});
  return [
    '# Claims register',
    '',
    `Generated by \`node org/claims.mjs\` from \`research/claims/*.json\`. ${claims.length} claims: ${Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(', ')}.`,
    'Only `verified` and `partial` claims may appear in customer-facing material; for `partial`, say the safe wording (ADR-006).',
    '',
    '| ID | Status | Category | Claim (or safe wording) | Source |',
    '| --- | --- | --- | --- | --- |',
    ...claims.filter((c) => !c.retired).map((c) => {
      const s = c.sources?.[0] ?? {};
      const text = c.status === 'partial' || c.status === 'refuted' ? `${esc(c.claim)} — **say:** ${esc(c.safeWording)}` : esc(c.claim);
      return `| ${c.id} | ${c.status} | ${c.category} | ${text} | [${esc(s.publisher || s.title)}](${s.url}) |`;
    }),
    '',
  ].join('\n');
}

function main() {
  const { claims, duplicates } = mergeShards();
  if (duplicates.length) { console.error(`duplicate claim ids:\n  ${duplicates.join('\n  ')}`); process.exit(1); }
  mkdirSync(join(ROOT, 'research'), { recursive: true });
  writeFileSync(join(ROOT, 'research', 'claims.json'), JSON.stringify(claims, null, 2) + '\n');
  writeFileSync(join(ROOT, 'research', 'claims.md'), renderClaims(claims));
  console.log(`claims: ${claims.length} merged from shards`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
