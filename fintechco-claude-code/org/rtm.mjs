#!/usr/bin/env node
// Requirements traceability: brief/requirements.json x board tickets.
//   node org/rtm.mjs            write brief/requirements.md and print coverage
//   node org/rtm.mjs --check    exit 1 unless every requirement has a done ticket (gate G5)
// A requirement is covered when at least one done ticket lists it in `requirements`.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Map each requirement to the tickets that cite it and whether one of them is done. */
export function coverage(spec, tickets) {
  return spec.requirements.map((r) => {
    const cited = tickets.filter((t) => (t.requirements ?? []).includes(r.id));
    const done = cited.filter((t) => t.status === 'done');
    return { ...r, tickets: cited.map((t) => t.id), doneTickets: done.map((t) => t.id), covered: done.length > 0 };
  });
}

/** Render the RTM as markdown. */
export function renderMarkdown(spec, rows) {
  const pct = rows.length ? Math.round((100 * rows.filter((r) => r.covered).length) / rows.length) : 0;
  const esc = (s) => String(s).replace(/\|/g, '\\|');
  const lines = [
    '# Requirements traceability matrix',
    '',
    `Generated by \`node org/rtm.mjs\` from \`brief/requirements.json\` and the board. Coverage: **${pct}%** (${rows.filter((r) => r.covered).length}/${rows.length}).`,
    '',
    `Source: ${spec.source}`,
    '',
    '## Deliverables',
    '',
    '| ID | Deliverable |',
    '| --- | --- |',
    ...Object.entries(spec.deliverables).map(([id, d]) => `| ${id} | ${esc(d)} |`),
    '',
    '## Requirements',
    '',
    '| ID | Requirement | Deliverables | Verification | Tickets (done) | Covered |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows.map((r) => `| ${r.id} | ${esc(r.text)} | ${r.deliverables.join(', ')} | ${esc(r.verify)} | ${r.doneTickets.join(', ') || '—'} | ${r.covered ? 'yes' : 'no'} |`),
    '',
  ];
  return lines.join('\n');
}

async function main() {
  const { listTickets } = await import('./fabric.mjs');
  const spec = JSON.parse(readFileSync(join(ROOT, 'brief', 'requirements.json'), 'utf8'));
  const rows = coverage(spec, listTickets());
  writeFileSync(join(ROOT, 'brief', 'requirements.md'), renderMarkdown(spec, rows));
  const missing = rows.filter((r) => !r.covered).map((r) => r.id);
  console.log(`RTM: ${rows.length - missing.length}/${rows.length} covered${missing.length ? '; open: ' + missing.join(', ') : ''}`);
  if (process.argv.includes('--check') && missing.length) process.exit(1);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main();
